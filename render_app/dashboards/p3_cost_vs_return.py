def style_scatter_axes(fig, xtitle, ytitle):
    fig.update_xaxes(title_text=xtitle, ticksuffix="%", showgrid=True, gridcolor=GRID)
    fig.update_yaxes(title_text=ytitle, ticksuffix="%")
    fig.update_layout(legend_title_text="")
