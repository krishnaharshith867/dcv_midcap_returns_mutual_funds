"""Convert Dashboard6_Fund_House_Scorecard.ipynb -> app.py (all 6 dashboards on one server).

Run from the project root:   python build_app.py
Then:                        gunicorn app:server
"""
import json, re, sys

NOTEBOOK = "Dashboard6_Fund_House_Scorecard.ipynb"
OUT = "app.py"

HEADER = '''# AUTO-GENERATED by build_app.py -- edit the notebook, then re-run build_app.py
import os
from flask import Flask
import plotly.graph_objects as _go

# No browser/notebook on a server: make notebook-only calls harmless
_go.Figure.show = lambda self, *a, **k: None
def display(*a, **k): pass

server = Flask(__name__)

PAGES = {}   # path -> title, filled in below

'''

FOOTER = '''

@server.route("/")
def index():
    links = "".join(f'<li><a href="{p}">{t}</a></li>' for p, t in PAGES.items())
    return ("<html><body style='font-family:sans-serif;background:#111;color:#eee;padding:40px'>"
            "<h1>Mid-cap mutual funds dashboards</h1><ul style='line-height:2'>" + links + "</ul></body></html>")

@server.route("/healthz")
def healthz():
    return "ok"

if __name__ == "__main__":
    server.run(port=int(os.environ.get("PORT", 8050)), debug=False)
'''

TITLES = {
    "": "Dashboard 1 - Fund companies overview",
    "2": "Dashboard 2 - Direct vs Regular cost gap",
    "3": "Dashboard 3 - Do Direct plans earn more?",
    "4": "Dashboard 4",
    "5": "Dashboard 5",
    "6": "Dashboard 6 - Fund house scorecard",
}

nb = json.load(open(NOTEBOOK, encoding="utf-8"))
chunks = []
for c in nb["cells"]:
    if c["cell_type"] != "code":
        continue
    src = "".join(c["source"])
    # drop the "try: import dash / except: !pip install" block
    src = re.sub(r"try:\s*\n\s*import dash,\s*dash_bootstrap_components\s*\nexcept ImportError:\s*\n\s*!pip[^\n]*\n", "", src)
    # drop remaining magics / shell lines
    src = "\n".join(l for l in src.split("\n") if not l.lstrip().startswith(("!", "%")))
    # remove app.run(...) calls (one level of parentheses inside is enough here)
    src = re.sub(r"^app\d?\.run\((?:[^()]|\([^()]*\))*\)\s*$", "", src, flags=re.M)
    chunks.append(src)

code = "\n\n".join(chunks)

# mount every Dash app on the shared Flask server under /, /d2/, /d3/ ...
def mount(m):
    n = m.group(1)
    path = "/d1/" if n == "" else f"/d{n}/"
    PAGES_LINE = f'PAGES["{path}"] = "{TITLES.get(n, "Dashboard " + (n or "1"))}"\n'
    return (f'{PAGES_LINE}app{n} = Dash(__name__, server=server, url_base_pathname="{path}", '
            f'external_stylesheets=[THEME])')

code, count = re.subn(r"app(\d?) = Dash\(__name__, external_stylesheets=\[THEME\]\)", mount, code)
print(f"mounted {count} Dash apps")

# the first app was called `app`; fine, keep names as in notebook
full = HEADER + code + FOOTER
compile(full, OUT, "exec")          # syntax check
open(OUT, "w", encoding="utf-8").write(full)
print("wrote", OUT)
