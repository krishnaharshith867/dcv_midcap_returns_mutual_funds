nb = json.load(open(NOTEBOOK, encoding="utf-8"))
chunks = []
for c in nb["cells"]:
    if c["cell_type"] != "code":
        continue
    src = "".join(c["source"])
    # drop the "try: import dash / except: !pip install" block
    src = re.sub(r"try:\s*\n\s*import dash,\s*dash_bootstrap_components\s*\nexcept ImportError:\s*\n\s*!pip[^\n]*\n", "", src)
    # drop remaining magics / shell lines
    src = "\n".join(l for l in src.split("\n") if not l.lstrip().startswith(("!", "%")))
    # remove app.run(...) calls (one level of parentheses inside is enough here)
    src = re.sub(r"^app\d?\.run\((?:[^()]|\([^()]*\))*\)\s*$", "", src, flags=re.M)
    chunks.append(src)

code = "\n\n".join(chunks)

# mount every Dash app on the shared Flask server under /, /d2/, /d3/ ...
def mount(m):
    n = m.group(1)
    path = "/d1/" if n == "" else f"/d{n}/"
    PAGES_LINE = f'PAGES["{path}"] = "{TITLES.get(n, "Dashboard " + (n or "1"))}"\n'
    return (f'{PAGES_LINE}app{n} = Dash(__name__, server=server, url_base_pathname="{path}", '
            f'external_stylesheets=[THEME])')

code, count = re.subn(r"app(\d?) = Dash\(__name__, external_stylesheets=\[THEME\]\)", mount, code)
print(f"mounted {count} Dash apps")
code, n_nav = re.subn(r"(app(\d?)\.layout = dbc\.Container\(\[)",
                      lambda m: m.group(1) + f'\n    nav_bar("/d{m.group(2) or 1}/"),', code)
print(f"nav bar added to {n_nav} layouts")
assert n_nav == count

# the first app was called `app`; fine, keep names as in notebook
